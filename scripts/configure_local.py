#!/usr/bin/env python3
"""Write tracks/a_small_molecule_discovery/config.local.yaml with absolute tool paths.

config.yaml is a portable template (bare executable names). This script finds the conda
environments created by scripts/bootstrap.sh (or your own with the same names) and writes
a machine-specific copy that Nextflow and the stage scripts read. The file is git-ignored.

Environment-variable overrides: PDAC_DD_ENV, PDAC_MD_ENV, BOLTZ_ENV, AMBER_ENV,
RETROCHIMERA_ENV, LBZIP2_ENV, ADMET_ENV (conda env names), RETROCHIMERA_CKPT (checkpoint directory).
"""
from __future__ import annotations

import os
import sys
from pathlib import Path

import yaml

REPO = Path(__file__).resolve().parents[1]
TRACK = REPO / "tracks" / "a_small_molecule_discovery"
sys.path.insert(0, str(TRACK / "scripts"))
from envtools import env_prefix, env_tool  # noqa: E402

DD = os.environ.get("PDAC_DD_ENV", "pdac-dd")
MD = os.environ.get("PDAC_MD_ENV", "pdac-md")
BOLTZ = os.environ.get("BOLTZ_ENV", "boltz2")
AMBER = [os.environ["AMBER_ENV"]] if os.environ.get("AMBER_ENV") else ["binding_energy", "amber", "pdac-md"]
RETRO = os.environ.get("RETROCHIMERA_ENV", "retrochimera")
LBZ = os.environ.get("LBZIP2_ENV", "lbz")

# (section, key) -> (conda env(s), executable)
MAP = {
    ("library", "lbzip2_exe"): (LBZ, "lbzip2"),
    ("boltz", "exe"): (BOLTZ, "boltz"),
    ("md", "python"): (MD, "python"),
    ("resistance", "python"): (MD, "python"),
    ("mmpbsa", "exe"): (AMBER, "MMPBSA.py"),
    ("mmpbsa", "antechamber"): (AMBER, "antechamber"),
    ("mmpbsa", "tleap"): (AMBER, "tleap"),
    ("retrosynthesis", "python"): (RETRO, "python"),
    ("admet", "exe"): (os.environ.get("ADMET_ENV", "admet-ai"), "admet_predict"),
    ("docking", "vina_exe"): (DD, "vina"),
    ("docking", "meeko_ligand_exe"): (DD, "mk_prepare_ligand.py"),
    ("resistance", "meeko_receptor_exe"): (DD, "mk_prepare_receptor.py"),
}


def main() -> None:
    cfg = yaml.safe_load((TRACK / "config.yaml").read_text())
    report = []
    for (sec, key), (env, exe) in MAP.items():
        value = env_tool(env, exe)
        cfg[sec][key] = value
        status = "ok" if os.path.isabs(value) else "NOT FOUND (left as bare name)"
        report.append(f"  {sec}.{key:<12} -> {value}   [{status}]")
    ckpt = os.environ.get("RETROCHIMERA_CKPT")
    if ckpt:
        cfg["retrosynthesis"]["model_dir"] = str(Path(ckpt).expanduser().resolve())
    dd_prefix = env_prefix(DD)
    out = TRACK / "config.local.yaml"
    header = "# Generated by scripts/configure_local.py. Machine specific. Do not commit.\n"
    out.write_text(header + yaml.safe_dump(cfg, sort_keys=False))
    print(f"wrote {out.relative_to(REPO)}")
    print("\n".join(report))
    print(f"  pdac-dd env prefix: {dd_prefix or 'NOT FOUND'}")


if __name__ == "__main__":
    main()
